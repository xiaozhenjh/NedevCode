import { PackagerDefinition } from '../types';

export const shellPackager: PackagerDefinition = {
  id: 'shell-bundle',
  name: 'Shell 执行脚本',
  description: '整合所有脚本文件的 POSIX 独立可执行 Bash 脚本，包含执行头与参数传递',
  category: 'local',
  supportedLanguages: ['shell'],
  artifactExtension: '.sh',
  icon: 'Terminal',
  isAvailableForProject: (project) => {
    return (
      project.language === 'shell' ||
      project.files.some((f) => f.name.endsWith('.sh') || f.name.endsWith('.bash'))
    );
  },
  package: async (project, _options, onProgress) => {
    onProgress?.({
      step: '正在整合 Shell 脚本文件...',
      percent: 40,
      status: 'running'
    });

    const entryFile =
      project.files.find((f) => f.isEntry && f.name.endsWith('.sh')) ||
      project.files.find((f) => f.name.endsWith('.sh')) ||
      project.files[0];

    const scriptBody = entryFile ? entryFile.content : '# Empty script\n';

    // 确保有正确的 Shebang 头部
    let content = scriptBody.trim();
    if (!content.startsWith('#!')) {
      content = `#!/usr/bin/env bash\n# Generated by Code Editor - ${project.title}\n\n` + content;
    }

    onProgress?.({
      step: '正在编译 POSIX 脚本格式...',
      percent: 85,
      status: 'running'
    });

    const blob = new Blob([content + '\n'], { type: 'application/x-sh;charset=utf-8' });
    const filename = `${project.title.replace(/[\s/\\?%*:|"<>]/g, '_') || 'script'}.sh`;

    onProgress?.({
      step: 'Shell 脚本打包完成',
      percent: 100,
      status: 'success',
      downloadName: filename
    });

    return {
      blob,
      filename
    };
  }
};
