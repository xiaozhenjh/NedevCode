import JSZip from 'jszip';
import { PackagerDefinition } from '../types';

/**
 * 1. Python 独立可执行 ZipApp 包 (.pyz - PEP 441 标准)
 * Python 原生支持直接运行 .pyz 文件 (例如: python app.pyz 或 ./app.pyz)
 */
export const pythonZipappPackager: PackagerDefinition = {
  id: 'python-zipapp',
  name: 'Python 可执行包',
  description: '基于 PEP 441 标准的 Python ZipApp (.pyz)，在安装有 Python 的设备上直接运行',
  category: 'local',
  supportedLanguages: ['python'],
  artifactExtension: '.pyz',
  icon: 'Terminal',
  isAvailableForProject: (project) => {
    return (
      project.language === 'python' ||
      project.files.some((f) => f.name.toLowerCase().endsWith('.py') || f.language === 'python')
    );
  },
  package: async (project, _options, onProgress) => {
    onProgress?.({
      step: '正在分析 Python 入口与模块依赖...',
      percent: 20,
      status: 'running'
    });

    const zip = new JSZip();

    // 查找入口文件 (main.py, app.py 或标记为 isEntry 的文件)
    const entryFile =
      project.files.find((f) => f.isEntry && f.name.endsWith('.py')) ||
      project.files.find((f) => f.name === 'main.py' || f.name === 'app.py') ||
      project.files.find((f) => f.name.endsWith('.py')) ||
      project.files[0];

    // 添加所有代码文件
    for (const file of project.files) {
      if (file.content && file.content.startsWith('data:') && file.content.includes(';base64,')) {
        const base64Data = file.content.split(';base64,')[1];
        zip.file(file.name, base64Data, { base64: true });
      } else {
        zip.file(file.name, file.content || '');
      }
    }

    // 确保根目录下包含 __main__.py 入口引导脚本
    if (!project.files.some((f) => f.name === '__main__.py')) {
      const entryModuleName = entryFile ? entryFile.name.replace(/\.py$/, '').replace(/\//g, '.') : 'main';
      const mainBootstrap = `#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Python ZipApp Bootstrapper
Generated by Code Editor
"""
import sys
import runpy

if __name__ == "__main__":
    try:
        runpy.run_module("${entryModuleName}", run_name="__main__", alter_sys=True)
    except Exception as e:
        print(f"执行出错: {e}", file=sys.stderr)
        sys.exit(1)
`;
      zip.file('__main__.py', mainBootstrap);
    }

    onProgress?.({
      step: '正在构建标准 PEP 441 归档结构...',
      percent: 60,
      status: 'running'
    });

    // 生成二进制 zip 数据
    const zipUint8 = await zip.generateAsync({
      type: 'uint8array',
      compression: 'DEFLATE',
      compressionOptions: { level: 9 }
    });

    // 为 Unix/Linux/macOS 添加直接执行的 Shebang 头部: #!/usr/bin/env python3\n
    const shebang = new TextEncoder().encode('#!/usr/bin/env python3\n');
    const combined = new Uint8Array(shebang.length + zipUint8.length);
    combined.set(shebang, 0);
    combined.set(zipUint8, shebang.length);

    const blob = new Blob([combined], { type: 'application/x-zipapp' });
    const filename = `${project.title.replace(/[\s/\\?%*:|"<>]/g, '_') || 'app'}.pyz`;

    onProgress?.({
      step: 'Python ZipApp 可执行包打包完成',
      percent: 100,
      status: 'success',
      downloadName: filename
    });

    return {
      blob,
      filename
    };
  }
};

/**
 * 2. Python 标准源码分发包 (sdist - 包含 pyproject.toml 与 requirements.txt)
 */
export const pythonSdistPackager: PackagerDefinition = {
  id: 'python-sdist',
  name: 'Python 源码分发包',
  description: '标准 Python 模块分发包，包含 pyproject.toml、setup.py 与 requirements.txt',
  category: 'local',
  supportedLanguages: ['python'],
  artifactExtension: '.zip',
  icon: 'Box',
  isAvailableForProject: (project) => {
    return (
      project.language === 'python' ||
      project.files.some((f) => f.name.toLowerCase().endsWith('.py') || f.language === 'python')
    );
  },
  package: async (project, _options, onProgress) => {
    onProgress?.({
      step: '正在构建 Python 标准工程分发目录...',
      percent: 25,
      status: 'running'
    });

    const zip = new JSZip();
    const cleanPkgName = (project.title || 'mypackage')
      .toLowerCase()
      .replace(/[^a-z0-9_]/g, '_');

    // 1. 添加所有代码文件
    for (const file of project.files) {
      if (file.content && file.content.startsWith('data:') && file.content.includes(';base64,')) {
        const base64Data = file.content.split(';base64,')[1];
        zip.file(file.name, base64Data, { base64: true });
      } else {
        zip.file(file.name, file.content || '');
      }
    }

    // 2. 自动生成 requirements.txt
    if (!project.files.some((f) => f.name === 'requirements.txt')) {
      const pipPkgs = project.packages || [];
      const reqContent = pipPkgs.length > 0 ? pipPkgs.join('\n') + '\n' : '# 项目无第三方依赖\n';
      zip.file('requirements.txt', reqContent);
    }

    // 3. 自动生成 pyproject.toml (PEP 518/621)
    if (!project.files.some((f) => f.name === 'pyproject.toml')) {
      const tomlContent = `[build-system]
requires = ["setuptools>=61.0"]
build-backend = "setuptools.build_meta"

[project]
name = "${cleanPkgName}"
version = "0.1.0"
description = "${project.description || 'Python application'}"
readme = "README.md"
requires-python = ">=3.8"
dependencies = [
${(project.packages || []).map((p) => `    "${p}",`).join('\n')}
]

[project.scripts]
${cleanPkgName} = "${cleanPkgName}.main:main"
`;
      zip.file('pyproject.toml', tomlContent);
    }

    // 4. 自动生成简要 README.md
    if (!project.files.some((f) => f.name.toLowerCase().startsWith('readme'))) {
      const readme = `# ${project.title}

${project.description || 'A Python application.'}

## 安装与运行

\`\`\`bash
pip install -r requirements.txt
python main.py
\`\`\`
`;
      zip.file('README.md', readme);
    }

    onProgress?.({
      step: '正在压缩生成 Python 标准分发包...',
      percent: 80,
      status: 'running'
    });

    const blob = await zip.generateAsync({
      type: 'blob',
      compression: 'DEFLATE',
      compressionOptions: { level: 6 }
    });

    const filename = `${cleanPkgName}-sdist.zip`;

    onProgress?.({
      step: 'Python 源码分发包构建完成',
      percent: 100,
      status: 'success',
      downloadName: filename
    });

    return {
      blob,
      filename
    };
  }
};
